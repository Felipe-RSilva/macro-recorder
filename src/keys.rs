use enigo::Key as EnigoKey;

/// Maps an `rdev` key name to the key that `enigo` can press.
pub fn key_from_name(name: &str) -> Option<EnigoKey> {
    let key = match name {
        "Escape" => EnigoKey::Escape,
        "Backspace" => EnigoKey::Backspace,
        "CapsLock" => EnigoKey::CapsLock,
        "ControlLeft" | "ControlRight" => EnigoKey::Control,
        "ShiftLeft" | "ShiftRight" => EnigoKey::Shift,
        "Alt" | "AltGr" => EnigoKey::Alt,
        "MetaLeft" | "MetaRight" => EnigoKey::Meta,
        "Return" | "KpReturn" => EnigoKey::Return,
        "Tab" => EnigoKey::Tab,
        "Space" => EnigoKey::Space,
        "Delete" => EnigoKey::Delete,
        "Insert" => EnigoKey::Insert,
        "Home" => EnigoKey::Home,
        "End" => EnigoKey::End,
        "PageUp" => EnigoKey::PageUp,
        "PageDown" => EnigoKey::PageDown,
        "UpArrow" => EnigoKey::UpArrow,
        "DownArrow" => EnigoKey::DownArrow,
        "LeftArrow" => EnigoKey::LeftArrow,
        "RightArrow" => EnigoKey::RightArrow,
        "F1" => EnigoKey::F1,
        "F2" => EnigoKey::F2,
        "F3" => EnigoKey::F3,
        "F4" => EnigoKey::F4,
        "F5" => EnigoKey::F5,
        "F6" => EnigoKey::F6,
        "F7" => EnigoKey::F7,
        "F8" => EnigoKey::F8,
        "F9" => EnigoKey::F9,
        "F10" => EnigoKey::F10,
        "F11" => EnigoKey::F11,
        "F12" => EnigoKey::F12,
        "KeyA" => EnigoKey::Unicode('a'),
        "KeyB" => EnigoKey::Unicode('b'),
        "KeyC" => EnigoKey::Unicode('c'),
        "KeyD" => EnigoKey::Unicode('d'),
        "KeyE" => EnigoKey::Unicode('e'),
        "KeyF" => EnigoKey::Unicode('f'),
        "KeyG" => EnigoKey::Unicode('g'),
        "KeyH" => EnigoKey::Unicode('h'),
        "KeyI" => EnigoKey::Unicode('i'),
        "KeyJ" => EnigoKey::Unicode('j'),
        "KeyK" => EnigoKey::Unicode('k'),
        "KeyL" => EnigoKey::Unicode('l'),
        "KeyM" => EnigoKey::Unicode('m'),
        "KeyN" => EnigoKey::Unicode('n'),
        "KeyO" => EnigoKey::Unicode('o'),
        "KeyP" => EnigoKey::Unicode('p'),
        "KeyQ" => EnigoKey::Unicode('q'),
        "KeyR" => EnigoKey::Unicode('r'),
        "KeyS" => EnigoKey::Unicode('s'),
        "KeyT" => EnigoKey::Unicode('t'),
        "KeyU" => EnigoKey::Unicode('u'),
        "KeyV" => EnigoKey::Unicode('v'),
        "KeyW" => EnigoKey::Unicode('w'),
        "KeyX" => EnigoKey::Unicode('x'),
        "KeyY" => EnigoKey::Unicode('y'),
        "KeyZ" => EnigoKey::Unicode('z'),
        "Num0" => EnigoKey::Unicode('0'),
        "Num1" => EnigoKey::Unicode('1'),
        "Num2" => EnigoKey::Unicode('2'),
        "Num3" => EnigoKey::Unicode('3'),
        "Num4" => EnigoKey::Unicode('4'),
        "Num5" => EnigoKey::Unicode('5'),
        "Num6" => EnigoKey::Unicode('6'),
        "Num7" => EnigoKey::Unicode('7'),
        "Num8" => EnigoKey::Unicode('8'),
        "Num9" => EnigoKey::Unicode('9'),
        "Minus" => EnigoKey::Unicode('-'),
        "Equal" => EnigoKey::Unicode('='),
        "BracketLeft" => EnigoKey::Unicode('['),
        "BracketRight" => EnigoKey::Unicode(']'),
        "BackSlash" => EnigoKey::Unicode('\\'),
        "Semicolon" => EnigoKey::Unicode(';'),
        "Quote" => EnigoKey::Unicode('\''),
        "Comma" => EnigoKey::Unicode(','),
        "Dot" => EnigoKey::Unicode('.'),
        "Slash" => EnigoKey::Unicode('/'),
        "BackQuote" => EnigoKey::Unicode('`'),
        _ => return None,
    };
    Some(key)
}
